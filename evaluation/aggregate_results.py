#!/usr/bin/env python3
"""Aggregate the baseline-vs-adaptive comparison's raw trial output into
evaluation/RESULTS.md.

Pure aggregation, no SITL/MAVSDK involved -- reads the `RESULT {json}`
lines each trial script prints (one line per trial, appended to a
per-scenario/per-condition file under ~/replan_trial_results/ during the
run, same convention established since decisions.md D15), and produces one
markdown table per scenario. Regenerating the report means re-running this
script over whatever's on disk, not hand-editing a table.

Usage: python aggregate_results.py [results_dir] [output_path]
Defaults match this project's established layout.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

DEFAULT_RESULTS_DIR = Path.home() / "replan_trial_results"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "RESULTS.md"

# (scenario label, condition label) -> results filename
GROUPS = {
    ("battery-critical (moderate, 12%)", "adaptive"): "eval_battery_moderate_adaptive.txt",
    ("battery-critical (moderate, 12%)", "baseline"): "eval_battery_moderate_baseline.txt",
    ("battery-critical (severe, ~5%)", "adaptive"): "eval_battery_severe_adaptive.txt",
    ("battery-critical (severe, ~5%)", "baseline"): "eval_battery_severe_baseline.txt",
    ("gps-degradation", "adaptive"): "eval_gps_adaptive.txt",
    ("gps-degradation", "baseline"): "eval_gps_baseline.txt",
    ("no-fly-zone (coverage mission)", "adaptive"): "eval_nfz_adaptive.txt",
    ("no-fly-zone (coverage mission)", "baseline"): "eval_nfz_baseline.txt",
}


def load_trials(path: Path) -> list[dict]:
    if not path.exists():
        return []
    trials = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line.startswith("RESULT "):
            continue
        try:
            d = json.loads(line[len("RESULT "):])
        except json.JSONDecodeError:
            continue
        d.pop("trace", None)
        d.pop("baseline_rtl_watch_trace", None)
        trials.append(d)
    return trials


def mean_sd(values: list[float]) -> str:
    if not values:
        return "n/a"
    if len(values) == 1:
        return f"{values[0]:.1f}"
    return f"{statistics.mean(values):.1f} +/- {statistics.pstdev(values):.1f}"


def summarize(trials: list[dict]) -> dict:
    n = len(trials)
    completion_pcts = [t["completion"]["percent"] for t in trials if "completion" in t]
    recovery_times = [t["t_to_safe_recovery_s"] for t in trials if t.get("t_to_safe_recovery_s") is not None]
    n_safe = sum(1 for t in trials if t.get("safe_confirmed"))
    n_zone_clean = [t["zone_never_entered"] for t in trials if "zone_never_entered" in t]
    return {
        "n": n,
        "completion": mean_sd(completion_pcts),
        "completion_n": len(completion_pcts),
        "recovery_time": mean_sd(recovery_times),
        "recovery_n": len(recovery_times),
        "safe_rate": f"{n_safe}/{n}" if n else "n/a",
        "zone_never_entered_rate": f"{sum(1 for z in n_zone_clean if z)}/{len(n_zone_clean)}" if n_zone_clean else "n/a",
    }


def main():
    results_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_RESULTS_DIR
    output_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUTPUT

    by_scenario: dict[str, dict[str, dict]] = {}
    for (scenario, condition), filename in GROUPS.items():
        trials = load_trials(results_dir / filename)
        by_scenario.setdefault(scenario, {})[condition] = summarize(trials)

    lines = [
        "# Baseline vs. Adaptive Replanning -- Evaluation Results",
        "",
        "Generated by `evaluation/aggregate_results.py` from raw trial JSON under "
        f"`{results_dir}` -- not hand-transcribed. Re-run the script to regenerate "
        "after any new trial batch. See `evaluation/DESIGN.md` for the methodology "
        "(baseline toggle, metric definitions, sample size) and `decisions.md` D22+ "
        "for the narrative write-up of what was actually observed, including the "
        "two real anomalies this comparison surfaced (severe-battery detection "
        "timing, and baseline RTL's behavior under GPS failure).",
        "",
    ]

    for scenario, conditions in by_scenario.items():
        lines.append(f"## {scenario}")
        lines.append("")
        lines.append("| condition | n | completion % (mean +/- sd) | time-to-safe-recovery s (mean +/- sd) | safe-confirmed rate | zone never entered |")
        lines.append("|---|---|---|---|---|---|")
        for condition in ("adaptive", "baseline"):
            s = conditions.get(condition, summarize([]))
            lines.append(
                f"| {condition} | {s['n']} | {s['completion']} (n={s['completion_n']}) "
                f"| {s['recovery_time']} (n={s['recovery_n']}) | {s['safe_rate']} | {s['zone_never_entered_rate']} |"
            )
        lines.append("")

    output_path.write_text("\n".join(lines))
    print(f"Wrote {output_path} ({sum(len(c) for c in by_scenario.values())} groups)")


if __name__ == "__main__":
    main()
